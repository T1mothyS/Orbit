import { test, expect } from '@playwright/test';
import { fixtureToken } from './auth-fixture';
import { checkVisual } from './visual-check';
const base = 'http://127.0.0.1:4187';
for (const [width, height] of [[390,844],[430,932],[768,1024],[1440,900]]) for (const theme of ['light','dark']) {
  test(`evolution and note theme ${width} ${theme}`, async ({ page, context }) => {
    const token = await fixtureToken(context, 'preview@example.invalid');
    await context.addInitScript(({ token, theme }) => { localStorage.setItem('aicalendar_token', token); localStorage.setItem('theme', theme); }, { token, theme });
    await page.setViewportSize({ width, height }); await page.emulateMedia({ reducedMotion: 'reduce' });
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/models', route => route.fulfill({ json: { models: [{ modelId: 'glm-5.1', displayName: '合成模型' }], defaultModel: 'glm-5.1' } }));
    await page.goto(base + '/assistant'); await page.getByRole('button', { name: '记事', exact: true }).click();
    await page.getByLabel('记事输入框', { exact: true }).fill('合成主题回归，不调用模型');
    const note = await page.locator('.orbit-compact-composer').evaluate(element => ({ border: getComputedStyle(element).borderColor, button: getComputedStyle(element.querySelector('.schedule-ai-send-button')!).backgroundColor }));
    expect(note.button).toBe(note.border);
    await checkVisual(page, `evolution-note-${width}-${theme}.png`, false, false);
    await page.getByRole('button', { name: '指令', exact: true }).click(); await page.getByLabel('AI 助手输入框', { exact: true }).fill('仅检查颜色，不发送');
    await expect(page.getByRole('button', { name: '发送', exact: true })).toBeEnabled();
    const command = await page.locator('.orbit-compact-composer').evaluate(element => ({ border: getComputedStyle(element).borderColor, button: getComputedStyle(element.querySelector('.schedule-ai-send-button')!).backgroundColor }));
    expect(command.button).toBe(command.border); expect(command.button).not.toBe(note.button);
    await page.goto(base + '/project?view=architecture&milestone=retrieval');
    await expect(page.locator('.evolution-overview-group')).toHaveCount(4);
    await expect(page.locator('.evolution-map-scroll')).toHaveCount(0);
    await page.locator('.evolution-node-list button').filter({ hasText: '知识检索' }).click();
    await expect(page.locator('.evolution-node-detail')).toContainText('知识检索'); await expect(page.locator('.evolution-related-list button').first()).toBeVisible();
    await page.locator('.evolution-overview').scrollIntoViewIfNeeded();
    expect(await page.locator('.evolution-overview').evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true);
    await checkVisual(page, `evolution-focus-${width}-${theme}.png`, false, false);
    await page.getByRole('button', { name: '查看完整架构', exact: true }).click();
    await expect(page.locator('.evolution-map [data-node]').first()).toBeVisible();
    expect(await page.locator('.evolution-map .is-muted').count()).toBeGreaterThan(0);
    expect(await page.locator('.evolution-map path.is-related').count()).toBeGreaterThan(0);
    await page.getByRole('button', { name: '返回概览', exact: true }).click();
    await page.locator('.evolution-metrics').scrollIntoViewIfNeeded(); await expect(page.locator('.evolution-test-evidence li')).toHaveCount(4);
    await expect(page.locator('.evolution-test-evidence')).toContainText('本里程碑未记录');
    await page.getByText('查看数据表与统计口径', { exact: true }).click(); await expect(page.locator('.evolution-table-scroll tbody tr')).toHaveCount(54);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await checkVisual(page, `evolution-evidence-${width}-${theme}.png`, false, false); expect(errors).toEqual([]);
  });
}
test('evolution story ends at latest, replays and keeps URL and history intact', async ({ page, context }) => {
  const token = await fixtureToken(context, 'preview-guards@example.invalid'); await context.addInitScript(token => localStorage.setItem('aicalendar_token', token), token);
  await page.setViewportSize({width:1440,height:900}); await page.clock.install(); await page.clock.pauseAt(new Date());
  await page.goto(base + '/project?view=architecture'); await expect(page.locator('.evolution-overview-group')).toHaveCount(4);
  const before = await page.evaluate(() => ({ url: location.href, length: history.length }));
  await page.clock.runFor(40000); await expect(page.locator('#evolution-milestone')).toHaveValue('nested-navigation-growth-quips');
  await expect(page.getByRole('button', { name: '继续播放', exact: true })).toBeVisible();
  expect(await page.evaluate(() => ({ url: location.href, length: history.length }))).toEqual(before);
  await page.getByRole('button', { name: '重新播放', exact: true }).click(); await expect(page.locator('#evolution-milestone')).toHaveValue('baseline');
  await page.getByRole('button', { name: '暂停架构播放', exact: true }).click();
  await page.getByRole('button', { name: '下一快照', exact: true }).click(); await expect(page.locator('#evolution-milestone')).toHaveValue('action-center');
  await page.getByRole('button', { name: '上一快照', exact: true }).click(); await expect(page.locator('#evolution-milestone')).toHaveValue('baseline');
});
